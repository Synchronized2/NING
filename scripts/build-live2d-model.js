const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const source = path.join(root, "assets/live2d/hiyori_pro_t11.moc3");
const target = path.join(root, "miniprogram/assets/live2d/hiyori/model-data.js");
const base64 = fs.readFileSync(source).toString("base64");
const content = `// Generated by scripts/build-live2d-model.js; do not edit manually.\nmodule.exports = ${JSON.stringify(base64)};\n`;
fs.writeFileSync(target, content);
console.log(`Generated ${path.relative(root, target)} (${Buffer.byteLength(content)} bytes)`);
