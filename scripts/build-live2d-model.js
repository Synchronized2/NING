const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const source = path.join(root, "assets/live2d/hiyori_pro_t11.moc3");
const target = path.join(root, "miniprogram/assets/live2d/hiyori/model-data.js");
const { decompress, crc32 } = require(path.join(root, "miniprogram/components/live2d-avatar/lz4"));
const model = fs.readFileSync(source);

function compress(bytes) {
  const encoded = [];
  const positions = new Map();
  const length = bytes.length;
  let anchor = 0;
  let cursor = 0;
  const extend = (size) => {
    while (size >= 255) { encoded.push(255); size -= 255; }
    encoded.push(size);
  };
  while (cursor + 12 <= length) {
    const key = bytes.readUInt32LE(cursor);
    const previous = positions.get(key);
    positions.set(key, cursor);
    if (previous === undefined || cursor - previous > 65535) { cursor++; continue; }
    let match = 4;
    while (cursor + match < length - 5 && bytes[previous + match] === bytes[cursor + match]) match++;
    const literals = cursor - anchor;
    encoded.push((Math.min(literals, 15) << 4) | Math.min(match - 4, 15));
    if (literals >= 15) extend(literals - 15);
    for (let index = anchor; index < cursor; index++) encoded.push(bytes[index]);
    const offset = cursor - previous;
    encoded.push(offset & 255, offset >> 8);
    if (match - 4 >= 15) extend(match - 4 - 15);
    cursor += match;
    anchor = cursor;
  }
  const literals = length - anchor;
  encoded.push(Math.min(literals, 15) << 4);
  if (literals >= 15) extend(literals - 15);
  for (let index = anchor; index < length; index++) encoded.push(bytes[index]);
  return Buffer.from(encoded);
}

const compressed = compress(model);
if (!Buffer.from(decompress(compressed, model.length)).equals(model)) throw new Error("Hiyori 模型压缩校验失败");
const content = `// Generated by scripts/build-live2d-model.js; do not edit manually.\nmodule.exports = ${JSON.stringify({ size: model.length, crc32: crc32(model), data: compressed.toString("base64") })};\n`;
fs.writeFileSync(target, content);
console.log(`Generated ${path.relative(root, target)} (${Buffer.byteLength(content)} bytes from ${model.length})`);
