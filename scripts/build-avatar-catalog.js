const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const root = path.resolve(__dirname, "..");
const mira = path.resolve(process.argv[2] || process.env.MIRA_COMPANION_DIR || "D:/gitlab/OpenAIQ/Mira-Companion");
const publicRoot = fs.realpathSync(path.join(mira, "public"));
const characters = require(path.join(mira, "shared/characters.json"));
const catalogPath = path.join(root, "miniprogram/utils/avatar-catalog.js");
const planPath = path.join(root, "artifacts/avatars/upload-plan.json");
const cloudRoot = "ning/avatars/v1";
const localPreviewRoot = path.join(root, "miniprogram/packages/avatars/previews");

function localPreview(id) {
  const file = path.join(localPreviewRoot, `${id}.jpg`);
  if (!fs.existsSync(file)) throw new Error(`缺少本地人物预览图：${file}；先运行 scripts/build-avatar-previews.ps1`);
  return `/packages/avatars/previews/${id}.jpg`;
}

function assetPath(relative) {
  const file = fs.realpathSync(path.resolve(publicRoot, relative.replace(/^\//, "")));
  if (!file.startsWith(publicRoot + path.sep)) throw new Error(`人物素材越界：${relative}`);
  return file;
}

function fileInfo(file, cloudPath) {
  const contents = fs.readFileSync(file);
  return {
    cloudPath,
    size: contents.length,
    sha1: crypto.createHash("sha1").update(contents).digest("hex"),
  };
}

const entries = [];
const uploads = [];
for (const character of characters.filter((item) => item.generation === 3)) {
  if (!/^[a-z0-9-]+$/.test(character.id)) throw new Error(`非法人物 ID：${character.id}`);
  if (character.id === "hiyori") {
    const previewFile = assetPath(decodeURIComponent(character.preview));
    const version = crypto.createHash("sha1").update(fs.readFileSync(previewFile)).digest("hex").slice(0, 12);
    const preview = fileInfo(previewFile, `${cloudRoot}/${character.id}/${version}/preview.png`);
    uploads.push({ ...preview, source: previewFile });
    entries.push({ id: character.id, name: character.name, family: character.family, builtIn: true, preview, localPreview: localPreview(character.id) });
    continue;
  }
  const manifestPath = assetPath(decodeURIComponent(character.url));
  const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
  const references = manifest.FileReferences;
  if (!references || !references.Moc || !Array.isArray(references.Textures) || !references.Textures.length) {
    throw new Error(`缺少 Cubism 3 模型或纹理：${character.id}`);
  }
  const sources = [
    assetPath(path.relative(publicRoot, path.resolve(path.dirname(manifestPath), references.Moc))),
    ...references.Textures.map((name) => assetPath(path.relative(publicRoot, path.resolve(path.dirname(manifestPath), name)))),
    assetPath(decodeURIComponent(character.preview)),
  ];
  const digest = crypto.createHash("sha1");
  sources.forEach((file) => digest.update(crypto.createHash("sha1").update(fs.readFileSync(file)).digest()));
  const version = digest.digest("hex").slice(0, 12);
  const base = `${cloudRoot}/${character.id}/${version}`;
  const names = ["model.moc3", ...references.Textures.map((_, index) => `texture-${index}.png`), "preview.png"];
  const files = sources.map((file, index) => fileInfo(file, `${base}/${names[index]}`));
  files.forEach((info, index) => uploads.push({ ...info, source: sources[index] }));
  entries.push({
    id: character.id,
    name: character.name,
    family: character.family,
    version,
    model: files[0],
    textures: files.slice(1, -1),
    preview: files[files.length - 1],
    localPreview: localPreview(character.id),
  });
}

if (entries.length !== 50 || entries[0].id !== "hiyori") {
  throw new Error(`预期 50 个 Cubism 3 人物（含 Hiyori），实际 ${entries.length} 个`);
}
fs.mkdirSync(path.dirname(planPath), { recursive: true });
fs.writeFileSync(catalogPath, `// Generated by scripts/build-avatar-catalog.js.\nmodule.exports = ${JSON.stringify(entries, null, 2)};\n`);
fs.writeFileSync(planPath, `${JSON.stringify({ source: mira, uploads }, null, 2)}\n`);
console.log(`Generated ${entries.length} characters and ${uploads.length} cloud files (${Math.round(uploads.reduce((sum, item) => sum + item.size, 0) / 1048576)} MiB).`);
